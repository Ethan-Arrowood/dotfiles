//! Commit signing: which key git should use, and the generated include that
//! configures it.
//!
//! Nothing is written into ~/.gitconfig itself. A machine with no key gets a
//! working git rather than one that fails on every commit.

use crate::ctx::Ctx;
use crate::{link, ui};
use anyhow::Result;
use std::path::PathBuf;

pub const EMAIL: &str = "ethan@arrowood.dev";

pub fn ssh_key_path(ctx: &Ctx) -> PathBuf {
    std::env::var_os("DOTFILES_SSH_KEY")
        .map(PathBuf::from)
        .unwrap_or_else(|| ctx.home.join(".ssh/id_ed25519"))
}

/// The public half. Appends `.pub`; `with_extension` would turn `my.key` into
/// `my.pub` by replacing the existing extension.
pub fn ssh_pub_path(ctx: &Ctx) -> PathBuf {
    let key = ssh_key_path(ctx);
    let mut s = key.into_os_string();
    s.push(".pub");
    PathBuf::from(s)
}

fn signing_include(ctx: &Ctx) -> PathBuf {
    ctx.state_dir.join("gitconfig.signing")
}

/// The public half of the ssh key, as `<type> <base64>` with no comment.
pub fn ssh_pub_key(ctx: &Ctx) -> Option<String> {
    let text = std::fs::read_to_string(ssh_pub_path(ctx)).ok()?;
    let mut parts = text.split_whitespace();
    Some(format!("{} {}", parts.next()?, parts.next()?))
}

/// Configure commit signing with this machine's own ssh key.
///
/// There is nothing to choose: a machine either has a key or it does not.
/// `ctx.signing` is false only when the user passed --no-signing.
///
/// Nothing is written into ~/.gitconfig -- the settings go in a generated
/// include, so a machine with no key gets a working git rather than one that
/// fails on every commit.
pub fn configure(ctx: &Ctx) -> Result<()> {
    let out = signing_include(ctx);

    if !ctx.signing {
        link::remove_if_present(ctx, &out)?;
        ui::skip("commit signing disabled (--no-signing)");
        return Ok(());
    }

    let pub_path = ssh_pub_path(ctx);
    if !pub_path.exists() {
        link::remove_if_present(ctx, &out)?;
        ui::warn("no ssh key on this machine — commits will not be signed");
        ui::detail("create the key above and re-run; it is picked up automatically");
        return Ok(());
    }

    // Exists but unparseable: git would be told to sign with nothing, failing
    // every commit -- which is what the existence check is meant to prevent.
    if ssh_pub_key(ctx).is_none() {
        link::remove_if_present(ctx, &out)?;
        ui::error(&format!(
            "{} exists but contains no usable key",
            ctx.pretty(&pub_path)
        ));
        return Ok(());
    }

    allowed_signers(ctx)?;
    let body = format!(
        "# Generated by `dotfiles install`. The [gpg] keys below are\n\
         # git's own naming -- `format = ssh` is what selects ssh signing.\n\
         [user]\n\tsigningkey = {}\n\
         [gpg]\n\tformat = ssh\n\
         [gpg \"ssh\"]\n\tallowedSignersFile = ~/.ssh/allowed_signers\n\
         [commit]\n\tgpgsign = true\n\
         [tag]\n\tgpgsign = true\n",
        pub_path.display()
    );
    link::write_file(ctx, &out, &body)?;
    ui::ok(&format!(
        "signing with ssh key {}",
        ctx.pretty(&ssh_key_path(ctx))
    ));
    Ok(())
}

/// allowed_signers is what lets `git log --show-signature` verify locally;
/// without it git can sign but not check its own signatures.
fn allowed_signers(ctx: &Ctx) -> Result<()> {
    let Some(pubkey) = ssh_pub_key(ctx) else {
        return Ok(());
    };
    let path = ctx.home.join(".ssh/allowed_signers");
    let existing = std::fs::read_to_string(&path).unwrap_or_default();
    let body = pubkey.split_whitespace().nth(1).unwrap_or_default();
    if !body.is_empty() && existing.contains(body) {
        ui::skip("allowed_signers already lists this key");
        return Ok(());
    }
    let line = format!("{EMAIL} namespaces=\"git\" {pubkey}\n");
    if ctx.dry_run {
        ui::dry("append this key to ~/.ssh/allowed_signers");
        return Ok(());
    }
    let mut text = existing;
    if !text.is_empty() && !text.ends_with('\n') {
        text.push('\n');
    }
    text.push_str(&line);
    std::fs::create_dir_all(ctx.home.join(".ssh"))?;
    std::fs::write(&path, text)?;
    link::chmod(&path, 0o600)?;
    ui::ok("added key to ~/.ssh/allowed_signers");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// with_extension would turn `my.key` into `my.pub`.
    #[test]
    fn pub_path_appends_rather_than_replaces_the_extension() {
        let ctx = Ctx::new(std::env::temp_dir(), true, true).unwrap();
        std::env::set_var("DOTFILES_SSH_KEY", "/tmp/my.key");
        let p = ssh_pub_path(&ctx);
        std::env::remove_var("DOTFILES_SSH_KEY");
        assert_eq!(p.to_string_lossy(), "/tmp/my.key.pub");
    }
}
