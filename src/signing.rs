//! Commit signing: which key git should use, and the generated include that
//! configures it.
//!
//! Nothing is written into ~/.gitconfig itself. A machine with no key gets a
//! working git rather than one that fails on every commit.

use crate::ctx::Ctx;
use crate::sys::{self, Cmd};
use crate::{link, ui};
use anyhow::Result;
use std::path::PathBuf;
use std::str::FromStr;

/// Public identifiers only. A key ID and an email are not key material.
pub const GPG_KEY: &str = "79007EFD4678CB94";
pub const EMAIL: &str = "ethan@arrowood.dev";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    Auto,
    Ssh,
    Gpg,
    Off,
}

impl FromStr for Mode {
    type Err = String;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "auto" => Ok(Mode::Auto),
            "ssh" => Ok(Mode::Ssh),
            "gpg" => Ok(Mode::Gpg),
            "off" => Ok(Mode::Off),
            other => Err(format!("expected auto|ssh|gpg|off, got '{other}'")),
        }
    }
}

impl Mode {
    pub fn from_env() -> Self {
        std::env::var("DOTFILES_SIGNING")
            .ok()
            .and_then(|v| v.parse().ok())
            .unwrap_or(Mode::Auto)
    }
    pub fn as_str(self) -> &'static str {
        match self {
            Mode::Auto => "auto",
            Mode::Ssh => "ssh",
            Mode::Gpg => "gpg",
            Mode::Off => "off",
        }
    }
}

pub fn ssh_key_path(ctx: &Ctx) -> PathBuf {
    std::env::var_os("DOTFILES_SSH_KEY")
        .map(PathBuf::from)
        .unwrap_or_else(|| ctx.home.join(".ssh/id_ed25519"))
}

pub fn gpg_key_present(key: &str) -> bool {
    sys::has("gpg")
        && Cmd::new("gpg")
            .args(["--list-secret-keys", key])
            .capture()
            .map(|c| c.ok)
            .unwrap_or(false)
}

/// What `auto` resolves to.
///
/// ssh comes first: every machine this repo sets up has an ssh key, it needs
/// no agent/pinentry/expiry management, and it signs inside a devcontainer
/// over a forwarded agent. gpg is the fallback when there is no ssh key.
pub fn resolve(ctx: &Ctx, requested: Mode) -> Mode {
    match requested {
        Mode::Auto => {
            if ssh_key_path(ctx).with_extension("pub").exists() {
                Mode::Ssh
            } else if gpg_key_present(GPG_KEY) {
                Mode::Gpg
            } else {
                Mode::Off
            }
        }
        other => other,
    }
}

fn signing_include(ctx: &Ctx) -> PathBuf {
    ctx.state_dir.join("gitconfig.signing")
}

/// The public half of the ssh key, as `<type> <base64>` with no comment.
pub fn ssh_pub_key(ctx: &Ctx) -> Option<String> {
    let text = std::fs::read_to_string(ssh_key_path(ctx).with_extension("pub")).ok()?;
    let mut parts = text.split_whitespace();
    Some(format!("{} {}", parts.next()?, parts.next()?))
}

pub fn configure(ctx: &Ctx, requested: Mode) -> Result<()> {
    let mode = resolve(ctx, requested);
    ui::step(&format!(
        "commit signing mode: {} (requested: {})",
        mode.as_str(),
        requested.as_str()
    ));
    let out = signing_include(ctx);

    match mode {
        Mode::Gpg => {
            if !gpg_key_present(GPG_KEY) {
                ui::error(&format!(
                    "signing mode gpg but key {GPG_KEY} is not in this keyring"
                ));
                ui::detail("restore it with: dotfiles key import --dashlane <ref>");
                link::remove_if_present(ctx, &out)?;
                return Ok(());
            }
            gpg_agent_conf(ctx)?;
            let program = sys::which("gpg")
                .map(|p| p.display().to_string())
                .unwrap_or_else(|| "gpg".into());
            let body = format!(
                "# Generated by `dotfiles install`: gpg key found in the keyring.\n\
                 [user]\n\tsigningkey = {GPG_KEY}\n\
                 [gpg]\n\tformat = openpgp\n\tprogram = {program}\n\
                 [commit]\n\tgpgsign = true\n\
                 [tag]\n\tgpgsign = true\n"
            );
            link::write_file(ctx, &out, &body)?;
            ui::ok(&format!("signing with gpg key {GPG_KEY}"));
        }

        Mode::Ssh => {
            let pub_path = ssh_key_path(ctx).with_extension("pub");
            if !pub_path.exists() {
                // Writing a config that points at a missing key makes every
                // commit fail, so refuse instead.
                ui::error(&format!(
                    "signing mode ssh but there is no key at {}",
                    ctx.pretty(&pub_path)
                ));
                ui::detail(&format!(
                    "generate one with:\n  ssh-keygen -t ed25519 -C \"{EMAIL}\" -f {}",
                    ctx.pretty(&ssh_key_path(ctx))
                ));
                link::remove_if_present(ctx, &out)?;
                return Ok(());
            }
            allowed_signers(ctx)?;
            let body = format!(
                "# Generated by `dotfiles install`: signing with the ssh key, no gpg needed.\n\
                 [user]\n\tsigningkey = {}\n\
                 [gpg]\n\tformat = ssh\n\
                 [gpg \"ssh\"]\n\tallowedSignersFile = ~/.ssh/allowed_signers\n\
                 [commit]\n\tgpgsign = true\n\
                 [tag]\n\tgpgsign = true\n",
                pub_path.display()
            );
            link::write_file(ctx, &out, &body)?;
            ui::ok(&format!(
                "signing with ssh key {}",
                ctx.pretty(&ssh_key_path(ctx))
            ));
        }

        Mode::Off => {
            link::remove_if_present(ctx, &out)?;
            ui::warn("no signing key on this machine — commits will not be signed");
            ui::detail(
                "Create the ssh key above and re-run; auto picks it up with no\n\
                 further configuration. To use gpg instead:\n  \
                 dotfiles key import --dashlane <ref>   (or: import <file.age>)",
            );
        }

        Mode::Auto => unreachable!("resolve() never returns Auto"),
    }
    Ok(())
}

/// allowed_signers is what lets `git log --show-signature` verify locally;
/// without it git can sign but not check its own signatures.
fn allowed_signers(ctx: &Ctx) -> Result<()> {
    let Some(pubkey) = ssh_pub_key(ctx) else {
        return Ok(());
    };
    let path = ctx.home.join(".ssh/allowed_signers");
    let existing = std::fs::read_to_string(&path).unwrap_or_default();
    let body = pubkey.split_whitespace().nth(1).unwrap_or_default();
    if !body.is_empty() && existing.contains(body) {
        ui::skip("allowed_signers already lists this key");
        return Ok(());
    }
    let line = format!("{EMAIL} namespaces=\"git\" {pubkey}\n");
    if ctx.dry_run {
        ui::dry("append this key to ~/.ssh/allowed_signers");
        return Ok(());
    }
    let mut text = existing;
    if !text.is_empty() && !text.ends_with('\n') {
        text.push('\n');
    }
    text.push_str(&line);
    std::fs::create_dir_all(ctx.home.join(".ssh"))?;
    std::fs::write(&path, text)?;
    link::chmod(&path, 0o600)?;
    ui::ok("added key to ~/.ssh/allowed_signers");
    Ok(())
}

fn gpg_agent_conf(ctx: &Ctx) -> Result<()> {
    if !sys::has("gpg") {
        return Ok(());
    }
    let conf = ctx.home.join(".gnupg/gpg-agent.conf");
    if conf.exists() {
        ui::skip("gpg-agent.conf exists");
        return Ok(());
    }
    let mut body = String::new();
    if let Some(p) = sys::which("pinentry-mac") {
        body.push_str(&format!("pinentry-program {}\n", p.display()));
    }
    body.push_str("default-cache-ttl 86400\nmax-cache-ttl 604800\n");
    if !ctx.dry_run {
        std::fs::create_dir_all(ctx.home.join(".gnupg"))?;
        link::chmod(&ctx.home.join(".gnupg"), 0o700)?;
    }
    link::write_file(ctx, &conf, &body)?;
    if !ctx.dry_run {
        let _ = Cmd::new("gpgconf")
            .args(["--reload", "gpg-agent"])
            .capture();
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn explicit_modes_are_not_rewritten() {
        let ctx = Ctx::new(std::env::temp_dir(), true, true).unwrap();
        assert_eq!(resolve(&ctx, Mode::Ssh), Mode::Ssh);
        assert_eq!(resolve(&ctx, Mode::Gpg), Mode::Gpg);
        assert_eq!(resolve(&ctx, Mode::Off), Mode::Off);
    }

    #[test]
    fn mode_parsing_rejects_nonsense() {
        assert_eq!("ssh".parse::<Mode>().unwrap(), Mode::Ssh);
        assert!("sshh".parse::<Mode>().is_err());
    }
}
