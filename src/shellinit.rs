//! Generates ~/.config/dotfiles/init.sh, the file ~/.zshrc sources.
//!
//! Fragments are enumerated here, at generate time, and emitted as explicit
//! `.` lines rather than globbed at startup. Globbing looked simpler but is
//! not portable between the two shells this has to serve: zsh does not
//! word-split unquoted parameters and aborts on an unmatched glob, and the
//! obvious guard for the latter (`setopt local_options null_glob`)
//! silently reverts every `setopt` a sourced fragment performs.
//!
//! Trade-off: a NEW fragment file needs `dotfiles install` re-run. Edits to
//! existing fragments take effect in the next shell.

use crate::ctx::Ctx;
use crate::layer::Layer;
use crate::link;
use anyhow::Result;
use std::fmt::Write as _;
use std::path::Path;

/// Single-quote a value for shell. A repo path containing `"`, `$` or a
/// backtick would otherwise break or inject into the generated init.sh, and
/// .zshrc sources that unconditionally, so every new shell would error.
pub(crate) fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Sorted list of files in `<layer>/<sub>` with the given extension.
fn fragments(layer_dir: &Path, sub: &str, ext: &str) -> Vec<String> {
    let dir = layer_dir.join(sub);
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return Vec::new();
    };
    let mut names: Vec<String> = entries
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.is_file() && p.extension().map(|x| x == ext).unwrap_or(false))
        .filter_map(|p| p.file_name().map(|n| n.to_string_lossy().into_owned()))
        .collect();
    names.sort();
    names
}

/// Escape for the inside of a double-quoted shell string.
fn dq_escape(s: &str) -> String {
    s.chars()
        .flat_map(|c| match c {
            '\\' | '"' | '$' | '`' => vec!['\\', c],
            _ => vec![c],
        })
        .collect()
}

pub fn render(ctx: &Ctx, profile: &str, layers: &[Layer]) -> String {
    let mut out = String::new();
    let names: Vec<&str> = layers.iter().map(|l| l.name).collect();

    let _ = writeln!(out, "# Generated by `dotfiles install`. Do not edit:");
    let _ = writeln!(out, "# re-run `dotfiles install` instead.");
    let _ = writeln!(
        out,
        "# Machine-local overrides belong in ~/.zshrc.local (sourced last)."
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "export DOTFILES_ROOT={}",
        sh_quote(&ctx.root.to_string_lossy())
    );
    let _ = writeln!(out, "export DOTFILES_LAYERS=\"{}\"", names.join(" "));
    let _ = writeln!(out, "export DOTFILES_PROFILE=\"{}\"", dq_escape(profile));

    for layer in layers {
        let dir = layer.path(ctx);
        let sh = fragments(&dir, "shell", "sh");
        let zsh = fragments(&dir, "zsh", "zsh");
        if sh.is_empty() && zsh.is_empty() {
            continue;
        }
        let _ = writeln!(out, "\n# --- {} ---", layer.name);
        for f in sh {
            let rel = format!("layers/{}/shell/{f}", layer.name);
            let _ = writeln!(out, ". \"$DOTFILES_ROOT\"/{}", sh_quote(&rel));
        }
        if !zsh.is_empty() {
            let _ = writeln!(out, "if [ -n \"${{ZSH_VERSION:-}}\" ]; then");
            for f in zsh {
                let rel = format!("layers/{}/zsh/{f}", layer.name);
                let _ = writeln!(out, "  . \"$DOTFILES_ROOT\"/{}", sh_quote(&rel));
            }
            let _ = writeln!(out, "fi");
        }
    }
    out
}

pub fn write(ctx: &Ctx, profile: &str, layers: &[Layer]) -> Result<()> {
    let content = render(ctx, profile, layers);
    link::write_file(ctx, &ctx.state_dir.join("init.sh"), &content)
}

/// Read back what a previous run recorded.
pub fn installed(ctx: &Ctx) -> Option<(String, Vec<String>)> {
    let text = std::fs::read_to_string(ctx.state_dir.join("init.sh")).ok()?;
    let get = |key: &str| -> Option<String> {
        text.lines()
            .find_map(|l| l.strip_prefix(&format!("export {key}=\"")))
            .and_then(|r| r.strip_suffix('"'))
            .map(|s| s.to_string())
    };
    let profile = get("DOTFILES_PROFILE")?;
    let layers = get("DOTFILES_LAYERS")?
        .split_whitespace()
        .map(String::from)
        .collect();
    Some((profile, layers))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::layer;

    fn test_ctx(root: &Path) -> Ctx {
        let mut c = Ctx::new(root.to_path_buf()).unwrap();
        c.root = root.to_path_buf();
        c
    }

    #[test]
    fn zsh_fragments_are_guarded_and_shell_fragments_are_not() {
        let tmp = std::env::temp_dir().join(format!("dfinit{}", std::process::id()));
        let ld = tmp.join("layers/core");
        std::fs::create_dir_all(ld.join("shell")).unwrap();
        std::fs::create_dir_all(ld.join("zsh")).unwrap();
        std::fs::write(ld.join("shell/10-a.sh"), "").unwrap();
        std::fs::write(ld.join("zsh/00-b.zsh"), "").unwrap();

        let ctx = test_ctx(&tmp);
        let core = layer::find("core").unwrap();
        let out = render(&ctx, "core", &[core]);

        let sh_line = ". \"$DOTFILES_ROOT\"/'layers/core/shell/10-a.sh'";
        let zsh_line = "  . \"$DOTFILES_ROOT\"/'layers/core/zsh/00-b.zsh'";
        assert!(out.contains(sh_line), "{out}");
        assert!(out.contains(zsh_line), "{out}");

        // The zsh fragment must sit inside the ZSH_VERSION guard; the shell one must not.
        let guard = out.find("if [ -n \"${ZSH_VERSION:-}\" ]; then").unwrap();
        assert!(out.find(sh_line).unwrap() < guard);
        assert!(out.find(zsh_line).unwrap() > guard);

        std::fs::remove_dir_all(&tmp).ok();
    }

    /// A fragment named `10-$HOME.sh` must be sourced by that literal name.
    #[test]
    fn fragment_names_are_quoted_literally() {
        let tmp = std::env::temp_dir().join(format!("dfinit3{}", std::process::id()));
        std::fs::create_dir_all(tmp.join("layers/core/shell")).unwrap();
        std::fs::write(tmp.join("layers/core/shell/10-$HOME.sh"), "").unwrap();
        let ctx = test_ctx(&tmp);
        let out = render(&ctx, "co$re", &[layer::find("core").unwrap()]);
        assert!(
            out.contains(". \"$DOTFILES_ROOT\"/'layers/core/shell/10-$HOME.sh'"),
            "{out}"
        );
        assert!(out.contains("DOTFILES_PROFILE=\"co\\$re\""), "{out}");
        std::fs::remove_dir_all(&tmp).ok();
    }

    #[test]
    fn a_repo_path_with_shell_metacharacters_is_quoted() {
        assert_eq!(sh_quote("/plain/path"), "'/plain/path'");
        assert_eq!(sh_quote(r#"/has "quote"/x"#), r#"'/has "quote"/x'"#);
        assert_eq!(sh_quote("/has $VAR/x"), "'/has $VAR/x'");
        assert_eq!(sh_quote("/it's/here"), r"'/it'\''s/here'");
    }

    #[test]
    fn no_runtime_globbing_or_word_splitting() {
        let tmp = std::env::temp_dir().join(format!("dfinit2{}", std::process::id()));
        std::fs::create_dir_all(tmp.join("layers/core/shell")).unwrap();
        std::fs::write(tmp.join("layers/core/shell/a.sh"), "").unwrap();
        let ctx = test_ctx(&tmp);
        let out = render(&ctx, "core", &[layer::find("core").unwrap()]);
        assert!(
            !out.contains('*'),
            "generated init must not glob at runtime:\n{out}"
        );
        assert!(
            !out.contains("for ") && !out.contains("$DOTFILES_LAYERS\n"),
            "generated init must not loop over an unquoted layer list:\n{out}"
        );
        std::fs::remove_dir_all(&tmp).ok();
    }
}
