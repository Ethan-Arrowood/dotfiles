#!/usr/bin/env bash
# Layer discovery, profile resolution, and generation of the shell init file.
#
# A layer is a directory under layers/ containing:
#   layer.conf   NAME / DESCRIPTION / PLATFORMS metadata (required)
#   install.sh   idempotent installation steps (optional)
#   home/        files symlinked into $HOME (optional)
#   shell/*.sh   POSIX fragments sourced by both bash and zsh (optional)
#   zsh/*.zsh    zsh-only fragments (optional)
#   Brewfile     package list consumed by brew_bundle (optional)
#
# Layer directories are prefixed with a sort key (00-, 10-, ...) that fixes
# both install order and shell-fragment source order. The key is not part of
# the layer's name.

layer_dir()  { printf '%s/layers/%s' "$DOTFILES_ROOT" "$(layer_slug "$1")"; }
layer_name() { basename "$1" | sed 's/^[0-9]*-//'; }

# Resolve a bare name ("core") to its prefixed directory name ("00-core").
layer_slug() {
  local want="$1" d
  for d in "$DOTFILES_ROOT"/layers/*/; do
    d="${d%/}"
    [[ "$(layer_name "$d")" == "$want" || "$(basename "$d")" == "$want" ]] && { basename "$d"; return 0; }
  done
  return 1
}

all_layers() {
  local d
  for d in "$DOTFILES_ROOT"/layers/*/; do
    [[ -f "${d}layer.conf" ]] || continue
    layer_name "${d%/}"
  done
}

# layer_meta <layer> <KEY> — read one field out of layer.conf.
layer_meta() {
  local dir key value
  dir="$(layer_dir "$1")" || return 1
  key="$2"
  value="$(sed -n "s/^${key}=//p" "$dir/layer.conf" | head -1)"
  printf '%s' "${value%\"}" | sed 's/^"//'
}

layer_supports_platform() {
  local platforms; platforms="$(layer_meta "$1" PLATFORMS)"
  [[ -z "$platforms" || "$platforms" == "any" ]] && return 0
  [[ " $platforms " == *" $(os_kind) "* ]]
}

# Profiles are newline lists of layer names; blanks and # comments ignored.
profile_layers() {
  local file="$DOTFILES_ROOT/profiles/$1"
  [[ -f "$file" ]] || return 1
  sed 's/#.*//' "$file" | tr -d ' \t' | grep -v '^$'
}

all_profiles() {
  local f
  for f in "$DOTFILES_ROOT"/profiles/*; do
    [[ -f "$f" ]] && basename "$f"
  done
}

# Order a list of layer names by their numeric directory prefix, de-duplicated.
sort_layers() {
  local l slug
  while read -r l; do
    [[ -z "$l" ]] && continue
    slug="$(layer_slug "$l")" || { log_warn "unknown layer: $l"; continue; }
    printf '%s\t%s\n' "$slug" "$(layer_name "$slug")"
  done | sort -u | sort -k1,1 | cut -f2
}

STATE_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/dotfiles"

# The generated init file is what makes composition work at runtime: it pins
# DOTFILES_ROOT for this machine and sources the enabled layers' fragments in
# order. It is machine state, deliberately not tracked in the repo.
write_init_file() {
  local layers=("$@") l dir slug f body=""

  # Fragments are enumerated here, at generate time, and emitted as explicit
  # `.` lines. Two zsh/bash differences make a runtime loop the wrong tool:
  # zsh does not word-split unquoted parameters, and it aborts on an unmatched
  # glob -- while the obvious guard for that, `setopt local_options null_glob`,
  # silently reverts every setopt a sourced fragment performs. Explicit lines
  # sidestep both and cost nothing at startup.
  #
  # Trade-off: a NEW fragment file needs `dotfiles install` to be re-run.
  # Edits to existing fragments take effect in the next shell, as usual.
  for l in "${layers[@]}"; do
    dir="$(layer_dir "$l")"
    slug="$(basename "$dir")"
    body+="
# --- $l ---
"
    for f in "$dir"/shell/*.sh; do
      [[ -r "$f" ]] || continue
      body+=". \"\$DOTFILES_ROOT/layers/$slug/shell/$(basename "$f")\"
"
    done

    local zsh_body=""
    for f in "$dir"/zsh/*.zsh; do
      [[ -r "$f" ]] || continue
      zsh_body+="  . \"\$DOTFILES_ROOT/layers/$slug/zsh/$(basename "$f")\"
"
    done
    if [[ -n "$zsh_body" ]]; then
      body+="if [ -n \"\${ZSH_VERSION:-}\" ]; then
$zsh_body"
      body+="fi
"
    fi
  done

  write_file "$STATE_DIR/init.sh" <<INIT
# Generated by \`dotfiles install\` on $(date -u '+%Y-%m-%dT%H:%M:%SZ').
# Do not edit: re-run \`dotfiles install\` instead.
# Machine-local overrides belong in ~/.zshrc.local (sourced last).

export DOTFILES_ROOT="$DOTFILES_ROOT"
export DOTFILES_LAYERS="${layers[*]}"
export DOTFILES_PROFILE="${DOTFILES_PROFILE:-custom}"
$body
INIT
}
