#!/usr/bin/env bash
# Core layer: make zsh and git usable anywhere.
#
# Sourced by bin/dotfiles with $LAYER_DIR set. Must be idempotent.

# The public identifier of the commit-signing key. Safe to commit: this is a
# key ID, not key material. The private key never lives in this repo.
CORE_SIGNING_KEY="${CORE_SIGNING_KEY:-79007EFD4678CB94}"

core_install_packages() {
  if has zsh && has git; then
    log_skip "zsh and git already installed"
    return 0
  fi
  local missing=()
  has zsh || missing+=(zsh)
  has git || missing+=(git)
  log_step "installing: ${missing[*]}"
  sys_install "${missing[@]}" || log_warn "could not install ${missing[*]} automatically"
}

core_set_login_shell() {
  local zsh_path; zsh_path="$(command -v zsh 2>/dev/null)" || return 0
  [[ "$SHELL" == "$zsh_path" ]] && { log_skip "login shell is already zsh"; return 0; }

  # chsh needs a password on macOS and is usually pointless in a container.
  if is_container; then
    log_skip "container: leaving login shell alone"
    return 0
  fi
  if ! grep -qx "$zsh_path" /etc/shells 2>/dev/null; then
    log_warn "$zsh_path is not in /etc/shells; add it before chsh"
    return 0
  fi
  if confirm "Change login shell to $zsh_path?"; then
    run "chsh -s $zsh_path" chsh -s "$zsh_path" || log_warn "chsh failed; run it yourself"
  else
    log_skip "login shell unchanged"
  fi
}

core_configure_gpg() {
  local out="$STATE_DIR/gitconfig.signing"

  if ! has gpg; then
    log_skip "gpg not installed — commit signing not configured"
    [[ -f "$out" ]] && run "removing stale $out" rm -f "$out"
    return 0
  fi

  # gpg-agent settings: keep the passphrase cached for a working day, and use
  # the graphical pinentry when it is available.
  local agent_conf="$HOME/.gnupg/gpg-agent.conf"
  if [[ ! -f "$agent_conf" ]]; then
    if [[ "${DOTFILES_DRY_RUN:-0}" != "1" ]]; then
      mkdir -p "$HOME/.gnupg" && chmod 700 "$HOME/.gnupg"
    fi
    {
      has pinentry-mac && printf 'pinentry-program %s\n' "$(command -v pinentry-mac)"
      printf 'default-cache-ttl 86400\nmax-cache-ttl 604800\n'
    } | write_file "$agent_conf"
    [[ "${DOTFILES_DRY_RUN:-0}" != "1" ]] && gpgconf --reload gpg-agent 2>/dev/null || true
  else
    log_skip "gpg-agent.conf exists"
  fi

  if gpg --list-secret-keys "$CORE_SIGNING_KEY" >/dev/null 2>&1; then
    write_file "$out" <<SIGNING
# Generated by \`dotfiles install\`. Present only because the signing key was
# found in this machine's keyring.
[user]
	signingkey = $CORE_SIGNING_KEY
[commit]
	gpgsign = true
[tag]
	gpgsign = true
[gpg]
	program = $(command -v gpg)
SIGNING
    log_ok "commit signing enabled with key $CORE_SIGNING_KEY"
  else
    [[ -f "$out" ]] && run "removing stale $out" rm -f "$out"
    log_warn "signing key $CORE_SIGNING_KEY is not in this keyring — commits will not be signed"
    cat <<'HOWTO'
       To enable signing on this machine, import the private key from your
       password manager or an existing machine, then re-run `dotfiles install`:

         # from the machine that has it
         gpg --export-secret-keys --armor 79007EFD4678CB94 > key.asc
         # on this machine
         gpg --import key.asc && rm key.asc
         gpg --edit-key 79007EFD4678CB94 trust   # choose 5 (ultimate), then quit

HOWTO
  fi
}

core_install_packages
core_configure_gpg
core_set_login_shell
