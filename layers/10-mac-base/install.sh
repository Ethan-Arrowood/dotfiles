#!/usr/bin/env bash
# macOS base: developer tooling that everything else assumes.

mac_xcode_clt() {
  if xcode-select -p >/dev/null 2>&1; then
    log_skip "xcode command line tools"
    return 0
  fi
  if [[ "${DOTFILES_DRY_RUN:-0}" == "1" ]]; then
    printf '%s  dry install xcode command line tools%s\n' "$_C_DIM" "$_C_RESET"
    return 0
  fi

  # The placeholder file makes softwareupdate list the CLT package.
  local sentinel="/tmp/.com.apple.dt.CommandLineTools.installondemand.in-progress"
  touch "$sentinel"
  local label
  label="$(softwareupdate -l 2>/dev/null \
    | grep -E '^\s*\*\s*Label: Command Line Tools' \
    | sed 's/^[^:]*: //' | sort -V | tail -1)"
  if [[ -n "$label" ]]; then
    log_step "installing $label (this takes a while)"
    softwareupdate --install "$label" --verbose || log_warn "softwareupdate failed"
  else
    log_warn "could not find a CLT package; falling back to the GUI installer"
    xcode-select --install 2>/dev/null || true
    log_warn "finish the GUI install, then re-run \`dotfiles install\`"
  fi
  rm -f "$sentinel"
}

mac_defaults() {
  # Only the settings worth losing an argument over. Anything cosmetic is left
  # to System Settings, where it is easier to change your mind.
  local -a settings=(
    "NSGlobalDomain ApplePressAndHoldEnabled -bool false"          # key repeat over accent menu
    "NSGlobalDomain KeyRepeat -int 2"
    "NSGlobalDomain InitialKeyRepeat -int 15"
    "NSGlobalDomain AppleShowAllExtensions -bool true"
    "NSGlobalDomain NSDocumentSaveNewDocumentsToCloud -bool false" # save to disk, not iCloud
    "com.apple.finder AppleShowAllFiles -bool true"
    "com.apple.finder ShowPathbar -bool true"
    "com.apple.finder ShowStatusBar -bool true"
    "com.apple.finder FXPreferredViewStyle -string Nlsv"           # list view
    "com.apple.finder _FXSortFoldersFirst -bool true"
    "com.apple.finder FXDefaultSearchScope -string SCcf"           # search current folder
    "com.apple.desktopservices DSDontWriteNetworkStores -bool true" # no .DS_Store on shares
    "com.apple.screencapture location -string $HOME/Downloads"
    "com.apple.screencapture disable-shadow -bool true"
    "com.apple.dock show-recents -bool false"
    "com.apple.dock autohide-delay -float 0"
  )
  local s
  for s in "${settings[@]}"; do
    # shellcheck disable=SC2086
    run "defaults write $s" defaults write $s
  done
  if [[ "${DOTFILES_DRY_RUN:-0}" != "1" ]]; then
    killall Finder Dock SystemUIServer 2>/dev/null || true
  fi
}

mac_computer_name() {
  local current; current="$(scutil --get ComputerName 2>/dev/null || echo '')"
  log_step "computer name is currently '${current:-unset}'"

  local name="${DOTFILES_COMPUTER_NAME:-}"
  if [[ -z "$name" ]]; then
    # Non-interactive runs never rename the machine; set DOTFILES_COMPUTER_NAME
    # to do it unattended.
    if [[ "${DOTFILES_ASSUME_YES:-0}" == "1" || "${DOTFILES_DRY_RUN:-0}" == "1" ]]; then
      log_skip "computer name unchanged (set DOTFILES_COMPUTER_NAME to rename)"
      return 0
    fi
    printf '%s   ?%s New computer name (blank to keep "%s"): ' "$_C_YELLOW" "$_C_RESET" "$current"
    read -r name </dev/tty || return 0
  fi
  [[ -z "$name" ]] && { log_skip "computer name unchanged"; return 0; }
  [[ "$name" == "$current" ]] && { log_skip "computer name already '$name'"; return 0; }

  # LocalHostName and NetBIOSName must be alphanumeric + hyphen only.
  local safe; safe="$(printf '%s' "$name" | tr ' ' '-' | tr -cd '[:alnum:]-')"
  run "ComputerName    = $name" as_root scutil --set ComputerName "$name"
  run "HostName        = $safe" as_root scutil --set HostName "$safe"
  run "LocalHostName   = $safe" as_root scutil --set LocalHostName "$safe"
  run "NetBIOSName     = $safe" as_root defaults write \
    /Library/Preferences/SystemConfiguration/com.apple.smb.server NetBIOSName -string "$safe"
}

mac_git_tools() {
  local out="$STATE_DIR/gitconfig.tools"
  if ! has delta; then
    [[ -f "$out" ]] && run "removing stale $out" rm -f "$out"
    log_skip "git-delta not installed; leaving the default pager"
    return 0
  fi
  write_file "$out" <<'DELTA'
# Generated by `dotfiles install` because git-delta is installed.
[core]
	pager = delta
[interactive]
	diffFilter = delta --color-only
[delta]
	navigate = true
	line-numbers = true
	side-by-side = false
	hyperlinks = true
[merge]
	conflictStyle = zdiff3
DELTA
}

mac_xcode_clt
ensure_homebrew
log_step "installing base packages"
brew_bundle "$LAYER_DIR/Brewfile"
log_step "applying macOS defaults"
mac_defaults
mac_git_tools
mac_computer_name
